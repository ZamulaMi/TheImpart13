import fs from 'fs';
import path from 'path';
import dotenv from 'dotenv';

dotenv.config({ override: true });

async function runPostBuild() {
  const distDir = path.resolve(process.cwd(), 'dist');
  const distIndexPath = path.join(distDir, 'index.html');
  const distShellPath = path.join(distDir, '_shell.html');
  const builtShellModulePath = path.resolve(process.cwd(), 'api', '_built_shell.ts');

  if (!fs.existsSync(distIndexPath)) {
    console.warn('[postbuild-seo] dist/index.html not found, skipping post-build generation.');
    return;
  }

  const cleanShellHtml = fs.readFileSync(distIndexPath, 'utf-8');

  // 1. Зберігаємо чистий Vite-шаблон із хешованими /assets/*.js та /assets/*.css
  fs.writeFileSync(distShellPath, cleanShellHtml, 'utf-8');
  fs.writeFileSync(
    builtShellModulePath,
    `// Auto-generated by scripts/postbuild-seo.mjs during npm run build\nexport const BUILT_HTML_SHELL: string = ${JSON.stringify(cleanShellHtml)};\n`,
    'utf-8'
  );

  // 2. Гарантуємо наявність статичного dist/robots.txt
  const publicRobotsPath = path.resolve(process.cwd(), 'public', 'robots.txt');
  const distRobotsPath = path.join(distDir, 'robots.txt');
  if (fs.existsSync(publicRobotsPath)) {
    fs.copyFileSync(publicRobotsPath, distRobotsPath);
    console.log('[postbuild-seo] Copied public/robots.txt -> dist/robots.txt');
  }

  // 3. Статична генерація dist/sitemap.xml та dist/news-sitemap.xml під час білду
  try {
    const { fetchSitemapSourceData, collectSitemapEntries, buildSitemapDocuments } = await import('../api/sitemap.ts');
    const sourceData = await fetchSitemapSourceData();
    const sitemapEntries = collectSitemapEntries(sourceData);
    const docs = buildSitemapDocuments(sitemapEntries);

    fs.writeFileSync(path.join(distDir, 'sitemap.xml'), docs.rootXml, 'utf-8');
    fs.writeFileSync(path.resolve(process.cwd(), 'public', 'sitemap.xml'), docs.rootXml, 'utf-8');
    console.log(`[postbuild-seo] Generated static sitemap.xml with ${sitemapEntries.length} entries.`);

    if (docs.isIndex && docs.partsXml.length > 0) {
      docs.partsXml.forEach((partXml, idx) => {
        fs.writeFileSync(path.join(distDir, `sitemap-${idx + 1}.xml`), partXml, 'utf-8');
      });
    }
  } catch (err) {
    console.warn('[postbuild-seo] Notice: static sitemap generation during build notice (runtime handler ready):', err);
  }

  try {
    const { fetchArticlesStrict } = await import('../api/sitemap.ts');
    const { collectNewsSitemapEntries, renderNewsSitemapXml } = await import('../api/news-sitemap.ts');
    const articles = await fetchArticlesStrict();
    const newsEntries = collectNewsSitemapEntries(articles);
    const newsXml = renderNewsSitemapXml(newsEntries);

    fs.writeFileSync(path.join(distDir, 'news-sitemap.xml'), newsXml, 'utf-8');
    fs.writeFileSync(path.resolve(process.cwd(), 'public', 'news-sitemap.xml'), newsXml, 'utf-8');
    console.log(`[postbuild-seo] Generated static news-sitemap.xml with ${newsEntries.length} entries.`);
  } catch (err) {
    console.warn('[postbuild-seo] Notice: static news-sitemap generation during build notice (runtime handler ready):', err);
  }

  // 4. Пре-рендеримо головну сторінку у dist/index.html з реальних даних БД (якщо доступно під час білду)
  try {
    const { generatePageResponse } = await import('../api/render-page.ts');
    const result = await generatePageResponse(
      { url: '/', originalUrl: '/', method: 'GET', query: {} },
      cleanShellHtml
    );
    if (result.status === 200 && result.html.includes('<html')) {
      fs.writeFileSync(distIndexPath, result.html, 'utf-8');
      console.log('[postbuild-seo] Pre-rendered dist/index.html successfully.');
    }
  } catch (err) {
    console.warn('[postbuild-seo] Notice: kept base dist/index.html (dynamic SSR active via /api/render-page):', err);
  }
}

runPostBuild();
